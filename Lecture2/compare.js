console.log(5 === 5);      // true
console.log(5 !== "5");    // true (different types, so "not equal" is true)
console.log(10 > 5);       // true
console.log(10 <= 10);    // true
console.log(5 == "5");    // true  ← loose equality it converts
console.log(5 === "5");   // false ← strict equality it check data types